  await expect(page.getByRole('heading', { name: 'Your source scenario' })).toBeVisible();
  await expect(page.getByRole('table')).toContainText('Half the seven-day average');
  await expect(page.getByRole('button', { name: 'Add AI evidence brief' })).toBeDisabled();
  await expect(page.getByText('Checkout is not activated on this host.', { exact: false })).toBeVisible();
  const scan = await new AxeBuilder({ page }).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze();
  expect(scan.violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('private-workspace.png'), fullPage: true });
  await page.getByText('Account, export and privacy', { exact: true }).click();
