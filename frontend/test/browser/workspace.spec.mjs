  await page.getByRole('button', { name: 'Download my account data' }).click();
  expect((await exported).suggestedFilename()).toBe('prophecy-account-export.json');
  const cookies = await context.cookies();
  const session = cookies.find(c => c.name === 'PROPHECYSESSID');
  expect(session.httpOnly).toBe(true); expect(session.sameSite).toBe('Lax'); expect(session.path).toBe('/prophecy/');
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back', exact: true })).toBeVisible();
